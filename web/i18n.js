export function normalizeLanguage(value){return value==='en'||value==='en-US'?'en':value==='zh'||value==='zh-CN'?'zh-CN':null;}
export function translate(key,language='zh-CN',values={}){
  const text=messages[key]?.[language==='en'?1:0]??key;
  return text.replace(/\{(\w+)\}/g,(match,name)=>Object.hasOwn(values,name)?String(values[name]):match);
}
let language='zh-CN';
export const t=(key,values)=>translate(key,language,values);
export const blockLabel=type=>messages[`block.${type}`]?t(`block.${type}`):type;
export const fieldLabel=key=>messages[`field.${key}`]?t(`field.${key}`):key;
export function initI18n(onChange=()=>{}){
  let saved;try{saved=localStorage.getItem('neko-language');}catch{/* Storage is optional. */}
  language=normalizeLanguage(new URLSearchParams(location.search).get('lang'))||normalizeLanguage(saved)||'zh-CN';
  const apply=()=>{
    document.documentElement.lang=language;
    for(const el of document.querySelectorAll('[data-i18n]'))el.textContent=t(el.dataset.i18n);
    for(const attr of ['aria-label','title','placeholder'])for(const el of document.querySelectorAll(`[data-i18n-${attr}]`))el.setAttribute(attr,t(el.getAttribute(`data-i18n-${attr}`)));
    document.querySelector('#language').value=language;
  };
  apply();
  document.querySelector('#language').addEventListener('change',event=>{
    const next=normalizeLanguage(event.target.value);if(!next)return;language=next;
    try{localStorage.setItem('neko-language',language);}catch{/* Storage is optional. */}
    // An explicit query must not pin a stale locale after the user switches.
    const url=new URL(location.href);if(url.searchParams.has('lang')){url.searchParams.set('lang',language);try{history.replaceState(null,'',url);}catch{}}
    apply();onChange();
  });
}
